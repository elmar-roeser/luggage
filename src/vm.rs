    #[test]
    fn marks_keep_content_and_mode() {
        let tmp = tempfile::tempdir().unwrap();
        let (a, x, gone) = (tmp.path().join("a b"), tmp.path().join("x"), tmp.path().join("gone"));
        fs::write(&a, "1").unwrap();
        fs::write(&x, "2").unwrap();
        fs::set_permissions(&x, fs::Permissions::from_mode(0o4755)).unwrap();
        let before = |p: &Path| fs::metadata(p).unwrap();
        let (ma, mx, md) = (before(&a), before(&x), before(tmp.path()));
        sleep(Duration::from_millis(20));
        let mut sh =
            Command::new("bash").arg("-c").arg(MARK).stdin(Stdio::piped()).spawn().unwrap();
        let input = format!("{}\n{}\n{}\n", a.display(), x.display(), gone.display());
        sh.stdin.take().unwrap().write_all(input.as_bytes()).unwrap();
        assert!(sh.wait().unwrap().success());
        for (p, m) in [(&a, &ma), (&x, &mx), (&tmp.path().to_path_buf(), &md)] {
            let now = fs::metadata(p).unwrap();
            assert_eq!(now.mode(), m.mode(), "{}", p.display());
            assert_eq!(now.mtime_nsec(), m.mtime_nsec());
            // the mark itself: a chmod changes the ctime
            assert_ne!((now.ctime(), now.ctime_nsec()), (m.ctime(), m.ctime_nsec()));
        }
        assert_eq!(fs::read_to_string(&a).unwrap(), "1");
    }

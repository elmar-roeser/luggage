//! The VM mode of the chest: a microVM (microvm.nix with qemu) per project.
//!
//! luggage writes a flake for the guest into `<state>/vm` and builds its runner there.
//! `/nix/store` and the project come from the host over virtiofs, so the dev environment works unchanged in the guest.

use std::fmt::Write as _;
use std::fs::{self, File};
use std::io::{BufRead, BufReader, Write};
use std::os::unix::fs::{MetadataExt, PermissionsExt};
use std::os::unix::net::UnixStream;
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, ExitStatus, Stdio};
use std::thread::sleep;
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail};

use crate::chest::{alive, sh_quote, wait_dead};
use crate::info;

/// Longest wait until the guest answers on ssh.
const READY_TIMEOUT: Duration = Duration::from_secs(60);
/// Tags of the virtiofs shares, as in the guest flake.
const TAGS: [&str; 2] = ["ro-store", "project"];

/// Template for the guest flake; `render` fills in the `@...@` placeholders.
const FLAKE: &str = r#"{
  description = "chest @NAME@ — microVM (generated by luggage)";

  inputs.nixpkgs.url = "@NIXPKGS@";
  inputs.microvm = {
    url = "github:microvm-nix/microvm.nix";
    inputs.nixpkgs.follows = "nixpkgs";
  };

  outputs = { self, nixpkgs, microvm }: {
    nixosConfigurations.chest = nixpkgs.lib.nixosSystem {
      system = "x86_64-linux";
      modules = [ microvm.nixosModules.microvm ({ pkgs, lib, ... }: let
        servicePackages = map (p: lib.getAttrFromPath (lib.splitString "." p) pkgs) [ "process-compose" @PACKAGES@ ];
      in {
        networking.hostName = @HOSTNAME@;
        networking.firewall.enable = false;
        documentation.enable = false;
        system.stateVersion = "26.05";
        # Each one saves 0.2 to 2 s of boot time: no mount rate limit, no status lines
        # on the slow serial console, and no terminal queries that wait 333 ms for an answer.
        boot.kernelParams = [
          "SYSTEMD_DEFAULT_MOUNT_RATE_LIMIT_BURST=1000"
          "systemd.show_status=false" "rd.systemd.show_status=false"
          "udev.log_level=3" "rd.udev.log_level=3"
          "systemd.tty.term.console=vt220" "systemd.tty.rows.console=24" "systemd.tty.columns.console=80"
        ];
        microvm = {
          hypervisor = "qemu";
          mem = 1024;
          vcpu = 2;
          socket = "control.socket";
          vsock.cid = @CID@;
          shares = [
            { proto = "virtiofs"; tag = "ro-store"; source = "/nix/store"; mountPoint = "/nix/.ro-store"; }
            { proto = "virtiofs"; tag = "project"; source = @PROJECT@; mountPoint = @PROJECT@; }
          ];
          volumes = [ { image = @VAR_IMG@; mountPoint = "/var"; size = 2048; } ];
          interfaces = [ { type = "user"; id = "usernet"; mac = "02:00:00:00:00:01"; } ];
        };
        # Same uid and gid as on the host: unprivileged virtiofsd maps only these two.
        users.groups.@USER@.gid = @GID@;
        users.users.@USER@ = {
          isNormalUser = true;
          uid = @UID@;
          group = @USER@;
          home = @HOME@;
          openssh.authorizedKeys.keys = [ @SSH_KEY@ ];
        };
        # The guest offers ssh over vsock by itself (systemd-ssh-generator); the host key lives on /var.
        services.openssh = {
          enable = true;
          openFirewall = false;
          hostKeys = [ { path = "/var/lib/ssh/ssh_host_ed25519_key"; type = "ed25519"; } ];
        };
        # Services run with process-compose as in the bubblewrap chest: same packages and host names,
        # /data on the VM disk (it survives a restart), sockets in /run/luggage, ports below 1024 allowed.
        # The services get the package paths themselves: e.g. mariadb-install-db finds its files only next to
        # its real binary, and the system profile does not link share/mysql.
        environment.systemPackages = servicePackages;
        environment.etc."luggage/path".text = lib.makeBinPath servicePackages;
        networking.hosts."127.0.0.1" = [ @HOSTS@ ];
        boot.kernel.sysctl."net.ipv4.ip_unprivileged_port_start" = 0;
        systemd.tmpfiles.rules = [
          "d /var/lib/luggage/data 0700 @UID@ @GID@ -"
          "L+ /data - - - - /var/lib/luggage/data"
          "d /run/luggage 0700 @UID@ @GID@ -"
        ];
      }) ];
    };
    # Everything luggage runs on the host, so it needs neither virtiofsd nor a new systemd there.
    packages.x86_64-linux.default = let pkgs = nixpkgs.legacyPackages.x86_64-linux; in pkgs.symlinkJoin {
      name = "chest-@NAME@";
      paths = [
        self.nixosConfigurations.chest.config.microvm.declaredRunner
        pkgs.virtiofsd
        (pkgs.writeShellScriptBin "chest-ssh-proxy" ''exec ${pkgs.systemd}/lib/systemd/systemd-ssh-proxy "$@"'')
      ];
    };
  };
}
"#;

/// Everything the guest flake needs.
#[derive(Debug)]
pub struct Guest<'a> {
    /// Name of the chest
    pub name: &'a str,
    /// Project directory; the guest mounts it at the same path
    pub project: &'a Path,
    /// URL of the nixpkgs input
    pub nixpkgs: &'a str,
    /// Disk image for `/var` in the guest
    pub var_img: &'a Path,
    /// Name of the guest user (the host user)
    pub user: &'a str,
    /// uid of the host user
    pub uid: u32,
    /// Primary gid of the host user
    pub gid: u32,
    /// Home directory of the host user
    pub home: &'a Path,
    /// Public ssh key that may log in
    pub ssh_key: &'a str,
    /// nixpkgs attributes the services need, e.g. `mariadb_1011`
    pub packages: &'a [String],
    /// Names that point to 127.0.0.1 in the guest
    pub hosts: &'a [String],
}

/// A Nix string literal. `${` is escaped so nothing gets interpolated.
fn nix_str(s: &str) -> String {
    let escaped = s.replace('\\', r"\\").replace('"', "\\\"").replace("${", "\\${");
    format!("\"{escaped}\"")
}

/// vsock address of the guest: stable per chest name, never one of the reserved CIDs 0 to 2.
pub fn cid(name: &str) -> u32 {
    // FNV-1a: std's hasher is not guaranteed to stay the same between Rust versions
    let hash =
        name.bytes().fold(0x811c_9dc5_u32, |h, b| (h ^ u32::from(b)).wrapping_mul(0x0100_0193));
    3 + hash % 0x7fff_0000
}

/// Host name of the guest; host names do not allow `_`.
fn hostname(name: &str) -> String {
    format!("chest-{}", name.replace('_', "-"))
}

/// Generates the content of the guest flake.
pub fn render(g: &Guest) -> String {
    let s = |p: &Path| nix_str(&p.to_string_lossy());
    FLAKE
        .replace("@NAME@", g.name)
        .replace("@NIXPKGS@", g.nixpkgs)
        .replace("@HOSTNAME@", &nix_str(&hostname(g.name)))
        .replace("@CID@", &cid(g.name).to_string())
        .replace("@PROJECT@", &s(g.project))
        .replace("@VAR_IMG@", &s(g.var_img))
        .replace("@USER@", &nix_str(g.user))
        .replace("@UID@", &g.uid.to_string())
        .replace("@GID@", &g.gid.to_string())
        .replace("@HOME@", &s(g.home))
        .replace("@SSH_KEY@", &nix_str(g.ssh_key.trim()))
        // last: these come from project files and must not be scanned for placeholders again
        .replace("@PACKAGES@", &list(g.packages))
        .replace("@HOSTS@", &list(g.hosts))
}

/// Nix strings separated by spaces, for a list.
fn list(items: &[String]) -> String {
    items.iter().map(|i| nix_str(i)).collect::<Vec<_>>().join(" ")
}

/// Creates the ssh key for the chest once and returns the public key.
fn ssh_key(dir: &Path) -> Result<String> {
    let key = dir.join("id_ed25519");
    if !key.exists() {
        let status = Command::new("ssh-keygen")
            .args(["-q", "-t", "ed25519", "-N", "", "-C", "luggage", "-f"])
            .arg(&key)
            .stdin(Stdio::null())
            .status()
            .context("cannot start ssh-keygen")?;
        if !status.success() {
            bail!("ssh-keygen failed");
        }
    }
    Ok(fs::read_to_string(key.with_extension("pub"))?)
}

/// Writes the guest flake into `dir/flake` and builds its runner as `dir/runner`.
/// Returns the path of the runner.
///
/// # Errors
/// If the key cannot be created or `nix build` fails.
pub fn build(
    name: &str,
    project: &Path,
    nixpkgs: &str,
    dir: &Path,
    packages: &[String],
    hosts: &[String],
) -> Result<PathBuf> {
    fs::create_dir_all(dir).with_context(|| format!("cannot create {}", dir.display()))?;
    let meta = fs::metadata("/proc/self")?;
    let user = std::env::var("USER").context("USER is not set")?;
    let home = crate::home();
    let ssh_key = ssh_key(dir)?;
    let var_img = dir.join("var.img");
    let flake = render(&Guest {
        name,
        project,
        nixpkgs,
        var_img: &var_img,
        user: &user,
        uid: meta.uid(),
        gid: meta.gid(),
        home: &home,
        ssh_key: &ssh_key,
        packages,
        hosts,
    });
    // Only flake.nix and flake.lock may be in here: nix copies the whole directory into the
    // world-readable store on every build, so the key and var.img stay one level up.
    let flake_dir = dir.join("flake");
    fs::create_dir_all(&flake_dir)?;
    let file = flake_dir.join("flake.nix");
    let runner = dir.join("runner");
    // flake.lock pins the inputs, so the same flake.nix gives the same runner
    if fs::read_to_string(&file).ok().as_deref() == Some(flake.as_str()) && runner.exists() {
        return Ok(runner);
    }
    fs::write(&file, flake)?;
    info("building the chest VM (nix build)");
    let status = Command::new("nix")
        .args(["build", "--out-link"])
        .arg(&runner)
        .arg(format!("path:{}", flake_dir.display()))
        .status()
        .context("cannot start nix")?;
    if !status.success() {
        bail!("nix build of the chest VM failed — flake: {}", file.display());
    }
    Ok(runner)
}

/// Socket of a virtiofs share, relative to the runtime dir. microvm.nix picks this name for qemu.
fn socket(name: &str, tag: &str) -> String {
    format!("{}-virtiofs-{tag}.sock", hostname(name))
}

/// ssh into the guest over vsock, without the user's ssh config (it could open a password dialog).
/// With `run`, connections share one master connection in the runtime dir. The remote command follows as further arguments.
fn ssh(name: &str, dir: &Path, run: Option<&Path>) -> Command {
    let proxy = dir.join("runner/bin/chest-ssh-proxy");
    let mut c = Command::new("ssh");
    if let Some(run) = run {
        c.args(["-o", "ControlMaster=auto", "-o", "ControlPersist=10m", "-o"])
            .arg(format!("ControlPath={}", run.join("cm.sock").display()));
    }
    c.args(["-F", "/dev/null", "-q", "-o", "BatchMode=yes", "-o", "IdentitiesOnly=yes"])
        // the host key is the guest's own and the connection never leaves this machine
        .args(["-o", "StrictHostKeyChecking=no", "-o", "UserKnownHostsFile=/dev/null"])
        .args(["-o", "LogLevel=ERROR", "-o", "ProxyUseFdpass=yes", "-i"])
        .arg(dir.join("id_ed25519"))
        .arg("-o")
        .arg(format!("ProxyCommand={} vsock/{} 22", sh_quote(&proxy.to_string_lossy()), cid(name)))
        .args(["-l", &std::env::var("USER").unwrap_or_default(), "vsock"]);
    c
}

/// Error for a vsock address that another VM already uses.
fn cid_error(name: &str) -> anyhow::Error {
    anyhow::anyhow!(
        "vsock address {} is taken by another VM — give the chest another name (`name` in chest.toml)",
        cid(name)
    )
}

/// Does some VM already use the vsock address of this chest? A free address fails at once with "No such device".
fn cid_taken(name: &str, dir: &Path) -> Result<bool> {
    let mut probe = Command::new(dir.join("runner/bin/chest-ssh-proxy"))
        .arg(format!("vsock/{}", cid(name)))
        .arg("22")
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
        .context("cannot start chest-ssh-proxy")?;
    for _ in 0..50 {
        if probe.try_wait()?.is_some() {
            let out = probe.wait_with_output()?;
            return Ok(!String::from_utf8_lossy(&out.stderr).contains("No such device"));
        }
        sleep(Duration::from_millis(10));
    }
    // still connected: something answers there
    let _ = probe.kill();
    let _ = probe.wait();
    Ok(true)
}

/// Stops leftover virtiofsd processes and removes their sockets.
/// A virtiofsd that outlived its VM keeps its socket locked, so the next start would fail.
fn stop_virtiofsd(name: &str, run: &Path) {
    for tag in TAGS {
        let pid_file = run.join(format!("virtiofsd-{tag}.pid"));
        if let Some(pid) =
            fs::read_to_string(&pid_file).ok().and_then(|p| p.trim().parse::<u32>().ok())
            && alive(pid)
        {
            let _ = Command::new("kill").arg(pid.to_string()).stderr(Stdio::null()).status();
            wait_dead(pid, 20);
        }
        let sock = run.join(socket(name, tag));
        for f in [pid_file, sock.with_extension("sock.pid"), sock] {
            let _ = fs::remove_file(f);
        }
    }
}

/// Starts virtiofsd for both shares and then the VM, all in the runtime dir `run`.
/// Writes the qemu PID to `pid_file` and returns once the guest answers on ssh.
///
/// # Errors
/// If a process cannot start or the guest does not become ready; the VM is stopped again then.
pub fn start(name: &str, project: &Path, dir: &Path, run: &Path, pid_file: &Path) -> Result<u32> {
    fs::create_dir_all(run).with_context(|| format!("cannot create {}", run.display()))?;
    fs::set_permissions(run, fs::Permissions::from_mode(0o700))?;
    // the readiness probe would otherwise reach the other VM and report success
    if cid_taken(name, dir)? {
        return Err(cid_error(name));
    }
    stop_virtiofsd(name, run);
    // a new guest has an empty home, so the environment must be sent again
    for f in ["control.socket", "cm.sock", "env.sent"] {
        let _ = fs::remove_file(run.join(f));
    }
    let bin = dir.join("runner/bin");
    // The store never changes, so the guest may cache it for good.
    for (tag, shared, cache) in
        [("ro-store", Path::new("/nix/store"), "always"), ("project", project, "auto")]
    {
        let log = File::create(run.join(format!("virtiofsd-{tag}.log")))?;
        let child = Command::new(bin.join("virtiofsd"))
            .arg(format!("--socket-path={}", socket(name, tag)))
            .arg("--shared-dir")
            .arg(shared)
            .args(["--sandbox=namespace", &format!("--cache={cache}")])
            .current_dir(run)
            // own process group: Ctrl-C in the terminal must not stop the VM
            .process_group(0)
            .stdin(Stdio::null())
            .stdout(log.try_clone()?)
            .stderr(log)
            .spawn()
            .context("cannot start virtiofsd")?;
        fs::write(run.join(format!("virtiofsd-{tag}.pid")), child.id().to_string())?;
    }
    for _ in 0..250 {
        if TAGS.iter().all(|t| run.join(socket(name, t)).exists()) {
            break;
        }
        sleep(Duration::from_millis(20));
    }
    if let Some(t) = TAGS.iter().find(|t| !run.join(socket(name, t)).exists()) {
        stop_virtiofsd(name, run);
        bail!(
            "virtiofsd for {t} does not start — log: {}",
            run.join(format!("virtiofsd-{t}.log")).display()
        );
    }
    let log = File::create(run.join("vm.log"))?;
    let mut vm = Command::new(bin.join("microvm-run"))
        .current_dir(run)
        .process_group(0)
        .stdin(Stdio::null())
        .stdout(log.try_clone()?)
        .stderr(log)
        .spawn()
        .context("cannot start the VM")?;
    let pid = vm.id();
    fs::write(pid_file, pid.to_string())?;
    if let Err(e) = wait_ready(name, dir, run, &mut vm) {
        stop(name, run, Some(pid));
        let _ = fs::remove_file(pid_file);
        return Err(e);
    }
    Ok(pid)
}

/// Waits until ssh into the guest works. Fails early if qemu stops.
fn wait_ready(name: &str, dir: &Path, run: &Path, vm: &mut Child) -> Result<()> {
    let log = run.join("vm.log");
    let end = Instant::now() + READY_TIMEOUT;
    while Instant::now() < end {
        if let Some(status) = vm.try_wait()? {
            let text = fs::read_to_string(&log).unwrap_or_default();
            if text.contains("guest cid") {
                return Err(cid_error(name));
            }
            bail!("VM stopped ({status}) — log: {}", log.display());
        }
        // no stdin: the probe must not eat input meant for a later command
        // no master connection: a failed first try would leave a broken one behind
        let probe = ssh(name, dir, None)
            .args(["-o", "ConnectTimeout=2", "true"])
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();
        if probe.is_ok_and(|s| s.success()) {
            return Ok(());
        }
        sleep(Duration::from_millis(50));
    }
    bail!("VM does not answer on ssh after {} s — log: {}", READY_TIMEOUT.as_secs(), log.display())
}

/// Asks the guest to power off through the QMP socket of qemu.
fn powerdown(control: &Path) -> std::io::Result<()> {
    let mut s = UnixStream::connect(control)?;
    s.set_read_timeout(Some(Duration::from_secs(2)))?;
    let mut reply = BufReader::new(s.try_clone()?);
    let mut line = String::new();
    // greeting, then one answer per command
    reply.read_line(&mut line)?;
    for cmd in ["qmp_capabilities", "system_powerdown"] {
        writeln!(s, "{{\"execute\":\"{cmd}\"}}")?;
        reply.read_line(&mut line)?;
    }
    Ok(())
}

/// Shuts the VM down cleanly, kills it as a last resort and stops virtiofsd.
pub fn stop(name: &str, run: &Path, pid: Option<u32>) {
    if let Some(pid) = pid {
        let clean = powerdown(&run.join("control.socket")).is_ok() && wait_dead(pid, 200);
        if !clean {
            for signal in ["-TERM", "-KILL"] {
                let _ = Command::new("kill").args([signal, &pid.to_string()]).status();
                if wait_dead(pid, 50) {
                    break;
                }
            }
        }
    }
    stop_virtiofsd(name, run);
    for f in ["control.socket", "cm.sock", "env.sent"] {
        let _ = fs::remove_file(run.join(f));
    }
}

/// The rc file in the guest: loads the dev environment and undoes what only makes sense in a Nix build.
fn render_rc(name: &str) -> String {
    format!(
        "source ~/.luggage/env.sh\n\
         unset NIX_BUILD_TOP TEMP TMP TEMPDIR SSL_CERT_FILE NIX_SSL_CERT_FILE\n\
         export TMPDIR=/tmp LUGGAGE_CHEST={}\n\
         PS1='[chest:{name}] \\w\\$ '\n",
        sh_quote(name)
    )
}

/// Does the host variable stay on the host? These describe the host session, point to host paths
/// or would override the dev environment in the guest.
fn host_only(var: &str) -> bool {
    const NAMES: [&str; 22] = [
        "PATH",
        "HOME",
        "USER",
        "LOGNAME",
        "SHELL",
        "PWD",
        "OLDPWD",
        "SHLVL",
        "_",
        "TMPDIR",
        "TEMP",
        "TMP",
        "TEMPDIR",
        "HOSTNAME",
        "MAIL",
        "DISPLAY",
        "IN_NIX_SHELL",
        "LANG",
        "LANGUAGE",
        "TERM",
        "SSL_CERT_FILE",
        "SSL_CERT_DIR",
    ];
    const PREFIXES: [&str; 22] = [
        "SSH_",
        "WAYLAND_",
        "XDG_",
        "DBUS_",
        "DIRENV_",
        "LUGGAGE_",
        "NIX_",
        "LC_",
        "COLORTERM",
        "TERM_PROGRAM",
        "GPG_",
        "KRB5",
        "DESKTOP_",
        "GDM",
        "GNOME",
        "QT_",
        "GTK_",
        "ZSH",
        "LESS",
        "CLAUDE",
        "ANTHROPIC",
        "OTEL",
    ];
    NAMES.contains(&var) || PREFIXES.iter().any(|p| var.starts_with(p))
}

/// Host variables that go along into the guest. Only names that the shell can `export`.
fn passed_env() -> Vec<(String, String)> {
    std::env::vars_os()
        .filter_map(|(k, v)| Some((k.into_string().ok()?, v.into_string().ok()?)))
        .filter(|(k, _)| {
            !host_only(k)
                && k.starts_with(|c: char| c.is_ascii_alphabetic() || c == '_')
                && k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
        .collect()
}

/// The shell command for the guest: dev environment, host variables, working directory, then the command.
/// Without a command it opens an interactive shell.
fn remote_command(cwd: &Path, env: &[(String, String)], cmd: &[String]) -> String {
    let mut r = String::from("source ~/.luggage/rc >/dev/null");
    for (k, v) in env {
        let _ = write!(r, "; export {k}={}", sh_quote(v));
    }
    let _ = write!(r, "; cd {} && exec", sh_quote(&cwd.to_string_lossy()));
    if cmd.is_empty() {
        r.push_str(" bash --rcfile ~/.luggage/rc -i");
    }
    for a in cmd {
        r.push(' ');
        r.push_str(&sh_quote(a));
    }
    r
}

/// The project packages in env.sh: the values of `nativeBuildInputs` and `buildInputs`, separated by spaces.
pub fn inputs_from_env_sh(env_sh: &str) -> String {
    let values: Vec<&str> = ["nativeBuildInputs", "buildInputs"]
        .iter()
        .filter_map(|var| {
            let line = env_sh.lines().find(|l| l.starts_with(&format!("{var}='")))?;
            line.split('\'').nth(1)
        })
        .collect();
    values.join(" ")
}

/// Programs in the `bin` directories of `inputs` (store paths separated by spaces).
/// Never bash or sh: scripts with `#!/usr/bin/env bash` would find the stand-in and call it forever.
fn project_programs(inputs: &str) -> Vec<String> {
    let mut names: Vec<String> = inputs
        .split_whitespace()
        .filter_map(|p| fs::read_dir(Path::new(p).join("bin")).ok())
        .flatten()
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .filter(|n| n != "bash" && n != "sh")
        .collect();
    names.sort();
    names.dedup();
    names
}

/// Writes one stand-in per program of `inputs` into `<run>/shims`; each runs the program in the guest.
/// The new set is built next to the old one and then swapped in.
pub fn write_shims(run: &Path, inputs: &str) -> Result<()> {
    let shims = run.join("shims");
    let fresh = run.join(format!("shims.{}", std::process::id()));
    let _ = fs::remove_dir_all(&fresh);
    fs::create_dir_all(&fresh)?;
    let exe = std::env::current_exe().context("cannot find the luggage program")?;
    for name in project_programs(inputs) {
        let file = fresh.join(&name);
        fs::write(
            &file,
            format!(
                "#!/bin/sh\nexec {} exec -- {} \"$@\"\n",
                sh_quote(&exe.to_string_lossy()),
                sh_quote(&name)
            ),
        )?;
        fs::set_permissions(&file, fs::Permissions::from_mode(0o755))?;
    }
    let _ = fs::remove_dir_all(&shims);
    fs::rename(&fresh, &shims)?;
    Ok(())
}

/// Copies `env_sh` and the rc file into the guest (`~/.luggage`) and `compose` to `/run/luggage/process-compose.yaml`,
/// unless that already happened for these files and this VM.
///
/// # Errors
/// If env.sh cannot be read or the copy over ssh fails.
pub fn sync_env(name: &str, dir: &Path, run: &Path, env_sh: &Path, compose: &Path) -> Result<()> {
    let sent = run.join("env.sent");
    let modified = |p: &Path| fs::metadata(p).and_then(|m| m.modified()).ok();
    let newest = modified(env_sh).max(modified(compose));
    if modified(&sent).is_some_and(|s| newest.is_some_and(|n| s >= n)) {
        return Ok(());
    }
    let status = ssh(name, dir, Some(run))
        .arg("-T")
        .arg(format!(
            "mkdir -p ~/.luggage && cat > ~/.luggage/env.sh && printf %s {} > ~/.luggage/rc && printf %s {} > /run/luggage/process-compose.yaml",
            sh_quote(&render_rc(name)),
            sh_quote(&fs::read_to_string(compose)?)
        ))
        .stdin(File::open(env_sh)?)
        .status()
        .context("cannot start ssh")?;
    if !status.success() {
        bail!("cannot copy the environment into the VM");
    }
    fs::write(sent, "")?;
    Ok(())
}

/// A shell `script` in the guest over the shared connection, without a terminal.
pub fn script(name: &str, dir: &Path, run: &Path, script: &str) -> Command {
    let mut c = ssh(name, dir, Some(run));
    c.arg("-T").arg(script);
    c
}

/// Runs `cmd` in the guest in `cwd` (a shell without a command) and returns its exit status.
///
/// # Errors
/// If ssh cannot start.
pub fn exec(name: &str, dir: &Path, run: &Path, cwd: &Path, cmd: &[String]) -> Result<ExitStatus> {
    use std::io::IsTerminal;
    // a terminal only for a terminal: otherwise output that goes to a pipe would get \r\n
    let tty = cmd.is_empty() || (std::io::stdin().is_terminal() && std::io::stdout().is_terminal());
    ssh(name, dir, Some(run))
        .arg(if tty { "-t" } else { "-T" })
        .arg(remote_command(cwd, &passed_env(), cmd))
        .status()
        .context("cannot start ssh")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn guest<'a>(name: &'a str, user: &'a str) -> Guest<'a> {
        Guest {
            name,
            project: Path::new("/home/u/projects/demo"),
            nixpkgs: "github:NixOS/nixpkgs/nixos-26.05",
            var_img: Path::new("/home/u/.local/share/luggage/chests/demo/vm/var.img"),
            user,
            uid: 1000,
            gid: 1000,
            home: Path::new("/home/u"),
            ssh_key: "ssh-ed25519 AAAA luggage\n",
            packages: &[],
            hosts: &[],
        }
    }

    #[test]
    fn renders_guest() {
        let f = render(&guest("my_app", "u"));
        assert!(f.contains("networking.hostName = \"chest-my-app\";"));
        assert!(f.contains(&format!("vsock.cid = {};", cid("my_app"))));
        assert!(f.contains(
            "source = \"/home/u/projects/demo\"; mountPoint = \"/home/u/projects/demo\";"
        ));
        assert!(f.contains("users.groups.\"u\".gid = 1000;"));
        assert!(f.contains("openssh.authorizedKeys.keys = [ \"ssh-ed25519 AAAA luggage\" ];"));
        // no placeholder left; "$@" in the proxy script is shell
        assert!(
            !f.split('@').skip(1).any(|rest| rest.starts_with(|c: char| c.is_ascii_uppercase()))
        );
    }

    #[test]
    fn renders_service_packages_and_hosts() {
        let (packages, hosts) =
            (["mariadb_1011".to_owned()], ["database".to_owned(), "mailer".to_owned()]);
        let f = render(&Guest { packages: &packages, hosts: &hosts, ..guest("demo", "u") });
        assert!(f.contains("pkgs) [ \"process-compose\" \"mariadb_1011\" ];"));
        assert!(
            f.contains("environment.etc.\"luggage/path\".text = lib.makeBinPath servicePackages;")
        );
        assert!(f.contains("networking.hosts.\"127.0.0.1\" = [ \"database\" \"mailer\" ];"));
        assert!(f.contains("\"d /run/luggage 0700 1000 1000 -\""));
    }

    #[test]
    fn nix_strings_are_escaped() {
        assert_eq!(nix_str(r#"a"b\c${d}"#), r#""a\"b\\c\${d}""#);
        assert!(render(&guest("x", "we\"ird")).contains("users.users.\"we\\\"ird\""));
    }

    #[test]
    fn cid_is_stable_and_valid() {
        assert_eq!(cid("demo"), cid("demo"));
        assert_ne!(cid("demo"), cid("demo2"));
        for name in ["", "a", "sparencon", "x".repeat(200).as_str()] {
            assert!((3..0x7fff_0003).contains(&cid(name)));
        }
    }

    #[test]
    fn remote_command_quotes_everything() {
        let env = [("APP_ENV".to_owned(), "test's".to_owned())];
        let cmd = ["php".to_owned(), "-r".to_owned(), "echo $x;".to_owned()];
        assert_eq!(
            remote_command(Path::new("/p/my dir"), &env, &cmd),
            r#"source ~/.luggage/rc >/dev/null; export APP_ENV='test'"'"'s'; cd '/p/my dir' && exec 'php' '-r' 'echo $x;'"#
        );
        assert!(
            remote_command(Path::new("/p"), &[], &[])
                .ends_with("exec bash --rcfile ~/.luggage/rc -i")
        );
    }

    #[test]
    fn host_variables_stay_on_the_host() {
        for v in [
            "PATH",
            "HOME",
            "SSH_AUTH_SOCK",
            "XDG_RUNTIME_DIR",
            "NIX_PATH",
            "SSL_CERT_FILE",
            "TERM",
        ] {
            assert!(host_only(v), "{v}");
        }
        for v in ["APP_ENV", "DATABASE_URL", "XDEBUG_MODE", "PHP_INI_SCAN_DIR"] {
            assert!(!host_only(v), "{v}");
        }
    }

    #[test]
    fn stand_ins_come_from_project_packages_without_shells() {
        let store = tempfile::tempdir().unwrap();
        let (php, bash) = (store.path().join("php"), store.path().join("bash"));
        for (pkg, progs) in [(&php, ["php", "php-fpm"]), (&bash, ["bash", "sh"])] {
            fs::create_dir_all(pkg.join("bin")).unwrap();
            for prog in progs {
                fs::write(pkg.join("bin").join(prog), "").unwrap();
            }
        }
        let env = format!(
            "buildInputs=''\nnativeBuildInputs='{} {}'\nexport nativeBuildInputs\n",
            php.display(),
            bash.display()
        );
        assert_eq!(project_programs(&inputs_from_env_sh(&env)), ["php", "php-fpm"]);
        assert_eq!(inputs_from_env_sh("PATH='/x'"), "");
    }

    #[test]
    fn rc_resets_build_only_variables() {
        let rc = render_rc("demo");
        assert!(rc.starts_with("source ~/.luggage/env.sh\n"));
        assert!(
            rc.contains("unset NIX_BUILD_TOP TEMP TMP TEMPDIR SSL_CERT_FILE NIX_SSL_CERT_FILE\n")
        );
        assert!(rc.contains("PS1='[chest:demo] \\w\\$ '"));
    }
}
